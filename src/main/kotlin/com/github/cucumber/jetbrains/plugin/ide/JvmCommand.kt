package com.github.cucumber.jetbrains.plugin.ide

import java.io.IOException
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import java.util.Locale
import java.util.TreeMap
import java.util.regex.Pattern

/**
 * Builds a Maven / Gradle command that runs only the selected feature or scenario, through the
 * module's Cucumber runner classes, instead of the whole test suite.
 */
object JvmCommand {

  private val RUNNER =
      Pattern.compile(
          """@RunWith\s*\(\s*Cucumber(?:\.class|::class)?\s*\)""" +
              """|@IncludeEngines\s*\(\s*(?:value\s*=\s*)?[{\[]?\s*"cucumber"""" +
              """|@Cucumber\b(?!Options|ContextConfiguration)""" +
              """|@CucumberOptions\b""")
  private val PLATFORM_RUNNER =
      Pattern.compile(
          """@IncludeEngines\s*\(\s*(?:value\s*=\s*)?[{\[]?\s*"cucumber"""" +
              """|@Cucumber\b(?!Options|ContextConfiguration)""")
  private val SOURCE_EXTENSIONS = listOf(".java", ".kt", ".groovy", ".scala")
  private const val MAX_SOURCE_SIZE = 200_000L

  /**
   * @param featurePath absolute path of the feature file, or null to run every feature
   * @param line 1-based scenario line, or 0 for the whole feature
   */
  fun build(base: String, featurePath: String?, line: Int): RunCommand =
      build(base, featurePath, line, isWindows())

  internal fun build(base: String, featurePath: String?, line: Int, windows: Boolean): RunCommand {
    val features =
        if (featurePath == null) listOf() else listOf(featurePath + (if (line > 0) ":$line" else ""))
    return build(base, features, Options(), windows)
  }

  /**
   * Extra Cucumber settings for [build].
   *
   * @param tags a tag expression (`cucumber.filter.tags`)
   * @param plugin a `cucumber.plugin` value, e.g. `message:<file>`
   * @param debugAddress `host:port` where a listening debugger waits for the test JVM
   * @param gradleInitScript path of the [GRADLE_INIT_SCRIPT] file (Gradle builds only)
   */
  class Options(
      val tags: String? = null,
      val plugin: String? = null,
      val debugAddress: String? = null,
      val gradleInitScript: String? = null,
  )

  /**
   * Gradle does not forward `-D` options to the test JVM: this init script copies the
   * `CUCUMBER_*` environment variables (or, when unset, the matching `-D` system properties of the
   * Gradle command line, so a copied command needs no environment) to the `cucumber.*` system
   * properties of every `Test` task (which then always runs), and attaches the test JVM to a
   * listening debugger.
   */
  val GRADLE_INIT_SCRIPT: String =
      """
      |// Generated by the Cucumber JetBrains plugin.
      |def cucumberSetting = { String name, String property ->
      |    def value = System.getenv(name)
      |    if (value == null || value.isEmpty()) {
      |        value = System.getProperty(property)
      |    }
      |    (value == null || value.isEmpty()) ? null : value
      |}
      |def cucumberProperties = [
      |    'CUCUMBER_FEATURES'   : 'cucumber.features',
      |    'CUCUMBER_FILTER_TAGS': 'cucumber.filter.tags',
      |    'CUCUMBER_PLUGIN'     : 'cucumber.plugin',
      |]
      |def cucumberValues = [:]
      |cucumberProperties.each { name, property ->
      |    def value = cucumberSetting(name, property)
      |    if (value != null) {
      |        cucumberValues[property] = value
      |    }
      |}
      |def cucumberDebug = cucumberSetting('CUCUMBER_JDWP_ADDRESS', '$GRADLE_DEBUG_PROPERTY')
      |def cucumberEngineOnly = cucumberSetting('CUCUMBER_JETBRAINS_ENGINE_ONLY', '$GRADLE_ENGINE_ONLY_PROPERTY')
      |allprojects {
      |    tasks.withType(Test).configureEach { task ->
      |        cucumberValues.each { property, value -> task.systemProperty(property, value) }
      |        if (cucumberDebug != null && !cucumberDebug.isEmpty()) {
      |            task.jvmArgs('-agentlib:jdwp=transport=dt_socket,server=n,suspend=y,address=' + cucumberDebug)
      |            task.maxParallelForks = 1
      |        }
      |        if (!cucumberValues.isEmpty() || cucumberDebug) {
      |            task.outputs.upToDateWhen(org.gradle.api.specs.Specs.SATISFIES_NONE)
      |        }
      |    }
      |    if (cucumberEngineOnly) {
      |        // Like Surefire's includeJUnit5Engines=cucumber: the engine runs cucumber.features
      |        // itself, so the @Suite runner must not run them a second time.
      |        afterEvaluate {
      |            tasks.withType(Test).configureEach { task ->
      |                if (task.options instanceof org.gradle.api.tasks.testing.junitplatform.JUnitPlatformOptions) {
      |                    task.options.includeEngines('cucumber')
      |                }
      |            }
      |        }
      |    }
      |}
      |"""
          .trimMargin()

  /**
   * @param features absolute feature files or directories, each optionally with `:line`
   *   suffixes; empty to run every feature
   */
  fun build(base: String, features: List<String>, options: Options): RunCommand =
      build(base, features, options, isWindows())

  internal fun build(
      base: String,
      featureList: List<String>,
      options: Options,
      windows: Boolean,
  ): RunCommand {
    val targets = featureList.map { splitLines(it) }
    val featurePath = targets.firstNotNullOfOrNull { localPath(it.first) }
    val root = Path.of(base).toAbsolutePath().normalize()
    val module =
        when {
          featurePath == null -> root
          // A directory (e.g. a module folder) may hold the build file itself.
          Files.isDirectory(featurePath) -> nearestBuildDir(featurePath, root)
          else -> nearestBuildDir(featurePath.parent, root)
        }
    val maven = isMaven(module, root)
    val buildRoot = buildRoot(module, root, maven)
    val featureArgs =
        targets.map { (path, lines) ->
          val local = localPath(path)
          (if (local == null) path else relativeFeature(module, local)) + lines
        }
    // An empty path is the module itself: run all of its features (Cucumber's default).
    val features = if (targets.isEmpty() || "" in featureArgs) null else featureArgs.joinToString(",")
    val allRunners = runnerFiles(module)
    // Each runner class would run cucumber.features again: keep the one closest to the feature.
    val runners =
        if (features == null || featurePath == null || allRunners.size < 2) allRunners.map { it.first }
        else listOf(closestRunner(module, featurePath, allRunners))

    val args = ArrayList<String>()
    val relativeModule = buildRoot.relativize(module).toString().replace('\\', '/')
    if (maven) {
      args.add(tool(buildRoot, root, if (windows) "mvnw.cmd" else "mvnw", "mvn"))
      args.add("test")
      if (relativeModule.isNotEmpty()) {
        args.addAll(listOf("-pl", relativeModule, "-am"))
      }
      if (runners.isEmpty()) {
        args.add("-Dsurefire.includeJUnit5Engines=cucumber")
      } else {
        args.add("-Dtest=" + runners.joinToString(","))
        if (features != null && platformRunner(module)) {
          // With cucumber.features set the Cucumber engine runs the feature itself; also running
          // the @Suite runner would execute every selected scenario twice.
          args.add("-Dsurefire.includeJUnit5Engines=cucumber")
        }
      }
      args.add("-Dsurefire.failIfNoSpecifiedTests=false")
      options.tags?.takeIf { it.isNotBlank() }?.let { args.add("-Dcucumber.filter.tags=$it") }
      options.plugin?.takeIf { it.isNotBlank() }?.let { args.add("-Dcucumber.plugin=$it") }
      options.debugAddress?.let {
        args.add(
            "-Dmaven.surefire.debug=-agentlib:jdwp=transport=dt_socket,server=n,suspend=y,address=$it")
      }
    } else {
      args.add(tool(buildRoot, root, if (windows) "gradlew.bat" else "gradlew", "gradle"))
      options.gradleInitScript?.let { args.addAll(listOf("--init-script", it)) }
      args.add(
          if (relativeModule.isEmpty()) "test" else ":" + relativeModule.replace('/', ':') + ":test")
      for (runner in runners) {
        args.addAll(listOf("--tests", runner))
      }
      // Gradle JVM system properties, which the init script reads when the environment variables
      // are missing (e.g. a copied command line run in a shell).
      options.tags?.takeIf { it.isNotBlank() }?.let { args.add("-Dcucumber.filter.tags=$it") }
      options.plugin?.takeIf { it.isNotBlank() }?.let { args.add("-Dcucumber.plugin=$it") }
      options.debugAddress?.let { args.add("-D$GRADLE_DEBUG_PROPERTY=$it") }
      if (engineOnly(features, options, module)) {
        args.add("-D$GRADLE_ENGINE_ONLY_PROPERTY=true")
      }
    }
    val env = LinkedHashMap<String, String>()
    if (features != null) {
      args.add("-Dcucumber.features=$features")
      // Gradle does not forward -D to the test JVM; Cucumber also reads CUCUMBER_FEATURES.
      env["CUCUMBER_FEATURES"] = features
    }
    if (!maven) {
      options.tags?.takeIf { it.isNotBlank() }?.let { env["CUCUMBER_FILTER_TAGS"] = it }
      options.plugin?.takeIf { it.isNotBlank() }?.let { env["CUCUMBER_PLUGIN"] = it }
      options.debugAddress?.let { env["CUCUMBER_JDWP_ADDRESS"] = it }
      if (engineOnly(features, options, module)) {
        // The init script then limits the JUnit Platform to the Cucumber engine (see Maven).
        env["CUCUMBER_JETBRAINS_ENGINE_ONLY"] = "true"
      }
    }
    return RunCommand(args, buildRoot.toString(), env)
  }

  private const val GRADLE_DEBUG_PROPERTY = "cucumber.jetbrains.jdwp"
  private const val GRADLE_ENGINE_ONLY_PROPERTY = "cucumber.jetbrains.engineOnly"

  private fun engineOnly(features: String?, options: Options, module: Path): Boolean =
      features != null && options.gradleInitScript != null && platformRunner(module)

  /**
   * The runner whose package shares the most leading directories with the feature's (sources and
   * resources both start below `src/<set>/<language>`), else the first by name.
   */
  private fun closestRunner(module: Path, feature: Path, runners: List<Pair<String, Path>>): String {
    val featureDirs = packageDirs(module, if (Files.isDirectory(feature)) feature else feature.parent)
    return runners
        .maxWith(
            compareBy<Pair<String, Path>> { (_, file) ->
                  val runnerDirs = packageDirs(module, file.parent)
                  featureDirs.zip(runnerDirs).takeWhile { (a, b) -> a == b }.size
                }
                .thenByDescending { it.first })
        .first
  }

  private fun packageDirs(module: Path, dir: Path?): List<String> {
    if (dir == null || !dir.startsWith(module)) {
      return emptyList()
    }
    val parts = module.relativize(dir).map { it.toString() }.filter { it.isNotEmpty() }
    return if (parts.size >= 3 && parts[0] == "src") parts.drop(3) else parts
  }

  /** `C:/a/b.feature:3:9` -> (`C:/a/b.feature`, `:3:9`). */
  internal fun splitLines(feature: String): Pair<String, String> {
    val match = LINE_SUFFIX.matcher(feature)
    return if (match.matches()) match.group(1) to match.group(2) else feature to ""
  }

  /** A local file path; null for URIs such as `classpath:a/b.feature`. */
  internal fun localPath(path: String): Path? {
    if (path.length > 2 && path.indexOf(':') > 1) {
      return null
    }
    return try {
      Path.of(path).toAbsolutePath().normalize()
    } catch (e: java.nio.file.InvalidPathException) {
      null
    }
  }

  private val LINE_SUFFIX: Pattern = Pattern.compile("""^(.*?)((?::\d+)+)$""")

  /** Relative to the module, where Surefire and Gradle start the test JVM (avoids `C:` URIs). */
  private fun relativeFeature(module: Path, feature: Path): String {
    val path = if (feature.startsWith(module)) module.relativize(feature) else feature
    return path.toString().replace('\\', '/')
  }

  /** Whether the runners use the JUnit Platform engine rather than JUnit 4's `@RunWith`. */
  internal fun platformRunner(module: Path): Boolean {
    val tests = module.resolve("src").resolve("test")
    if (!Files.isDirectory(tests)) {
      return false
    }
    return try {
      Files.walk(tests, 30).use { files ->
        files
            .filter { Files.isRegularFile(it) }
            .filter { isSource(it) }
            .map { read(it) }
            .anyMatch { text -> text != null && PLATFORM_RUNNER.matcher(text).find() }
      }
    } catch (e: IOException) {
      false
    } catch (e: RuntimeException) {
      false
    }
  }

  /** The Cucumber runner classes under `module/src/test`: simple name and file, by name. */
  private fun runnerFiles(module: Path): List<Pair<String, Path>> {
    val tests = module.resolve("src").resolve("test")
    if (!Files.isDirectory(tests)) {
      return emptyList()
    }
    val runners = TreeMap<String, Path>()
    try {
      Files.walk(tests, 30).use { files ->
        files
            .filter { Files.isRegularFile(it) }
            .filter { isSource(it) }
            .forEach { file ->
              val text = read(file)
              if (text != null && RUNNER.matcher(text).find()) {
                val name = file.fileName.toString()
                runners.putIfAbsent(name.substring(0, name.lastIndexOf('.')), file)
              }
            }
      }
    } catch (ignored: IOException) {
      // unreadable test tree: fall back to engine selection
    } catch (ignored: RuntimeException) {
      // unreadable test tree: fall back to engine selection
    }
    return runners.map { (name, file) -> name to file }
  }

  private fun isSource(file: Path): Boolean {
    val name = file.fileName.toString().lowercase(Locale.ROOT)
    return SOURCE_EXTENSIONS.any { name.endsWith(it) }
  }

  private fun read(file: Path): String? =
      try {
        if (Files.size(file) > MAX_SOURCE_SIZE) null
        else Files.readString(file, StandardCharsets.UTF_8)
      } catch (e: IOException) {
        null
      } catch (e: RuntimeException) {
        null
      }

  private fun hasBuildFile(dir: Path): Boolean =
      Files.isRegularFile(dir.resolve("pom.xml")) ||
          Files.isRegularFile(dir.resolve("build.gradle")) ||
          Files.isRegularFile(dir.resolve("build.gradle.kts"))

  /** The closest directory (inside `root`) with a build file, else `root`. */
  private fun nearestBuildDir(start: Path?, root: Path): Path {
    var dir = start
    while (dir != null && dir.startsWith(root)) {
      if (hasBuildFile(dir)) {
        return dir
      }
      dir = dir.parent
    }
    return root
  }

  private fun isMaven(module: Path, root: Path): Boolean {
    if (Files.isRegularFile(module.resolve("pom.xml"))) {
      return true
    }
    if (hasBuildFile(module)) {
      return false
    }
    return Files.isRegularFile(root.resolve("pom.xml")) ||
        !(Files.isRegularFile(root.resolve("build.gradle")) ||
            Files.isRegularFile(root.resolve("build.gradle.kts")) ||
            Files.isRegularFile(root.resolve("settings.gradle")) ||
            Files.isRegularFile(root.resolve("settings.gradle.kts")))
  }

  /** The topmost directory between `module` and `root` that belongs to the same build. */
  private fun buildRoot(module: Path, root: Path, maven: Boolean): Path {
    var top = module
    var dir: Path? = module
    while (dir != null && dir.startsWith(root)) {
      val member =
          if (maven) Files.isRegularFile(dir.resolve("pom.xml"))
          else
              Files.isRegularFile(dir.resolve("settings.gradle")) ||
                  Files.isRegularFile(dir.resolve("settings.gradle.kts")) ||
                  Files.isRegularFile(dir.resolve("build.gradle")) ||
                  Files.isRegularFile(dir.resolve("build.gradle.kts"))
      if (member) {
        top = dir
      }
      dir = dir.parent
    }
    return top
  }

  private fun tool(buildRoot: Path, root: Path, wrapper: String, fallback: String): String {
    for (dir in listOf(buildRoot, root)) {
      val candidate = dir.resolve(wrapper)
      if (Files.isRegularFile(candidate)) {
        return candidate.toString()
      }
    }
    return fallback
  }

  private fun isWindows(): Boolean =
      System.getProperty("os.name", "").lowercase(Locale.ROOT).startsWith("windows")
}
